"""Render complete skills from their single editable procedure source."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / 'kit'

def render(path):
    old = path.read_text(encoding='utf-8-sig')
    front = old.split('---', 2)[1].strip()
    name = path.parent.name.removeprefix('highgrade-')
    procedure = KIT / 'procedures' / (name + '.md')
    body = procedure.read_text(encoding='utf-8-sig').strip()
    # References are resolved from the active release, not from the profile's
    # skill directory. Plain paths work in both the source and installed skill.
    def reference(m):
        label, target = m.groups()
        if '://' in target:
            return m.group(0)
        target = target[3:] if target.startswith('../') else 'procedures/' + target
        return f'{label} (`{target}` in the active release)'
    body = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', reference, body)
    entry = (
        'On first entry, read release `rules.md`. Global update needs no project. '
        'For project work, read its AGENTS and local instruction if present; '
        'their absence does not block Update. Check'
        if name == 'update' else
        'On first entry, read release `rules.md`, AGENTS and the local project instruction; check'
    )
    missing_instruction = '' if name == 'update' else ' Missing project instruction during init is expected.'
    return f'''---
{front}
---

<!-- Generated by scripts/render-skills.py from procedures/{name}.md. -->

Profile comes from `<profile>/.agents/skills/highgrade-{name}/SKILL.md`; project root comes from the user's workspace. `<profile>/.highgrade/global/active.json` names the active release. Its CLI and materials are in `<profile>/.highgrade/global/releases/<release>/`. CLI is `highgrade` on Linux and `highgrade.exe` on Windows. {entry} `global-status --profile <profile>` with that release CLI. Reuse verified context under rules.md.{missing_instruction} Report actual installation errors. The stage instruction follows; do not reread `procedures/{name}.md`. All material paths are relative to active-release root.

{body}
'''

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = []
    for path in sorted((KIT / 'skills').glob('highgrade-*/SKILL.md')):
        expected = render(path)
        if path.read_text(encoding='utf-8-sig') != expected:
            changed.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(expected, encoding='utf-8', newline='\n')
    manifest_path = KIT / 'manifest.json'
    manifest = json.loads(manifest_path.read_text(encoding='utf-8-sig'))
    hashes = {rel: hashlib.sha256((KIT / rel).read_bytes()).hexdigest() for rel in manifest['files']}
    if args.check:
        if changed or hashes != manifest['files']:
            raise SystemExit('Stale generated skills or manifest: ' + ', '.join(changed))
        print('Skills and manifest are current')
    else:
        manifest['files'] = hashes
        manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
        print(f'Rendered {len(changed)} skills; refreshed manifest')

if __name__ == '__main__':
    main()
